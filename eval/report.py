"""Aggregates eval/results/*.json (produced by `pytest eval/`) into eval/report.md.

Run after the eval suite: `pytest eval/ && python -m eval.report`
"""

import json
import os
import statistics

RESULTS_DIR = os.path.join(os.path.dirname(__file__), "results")
REPORT_PATH = os.path.join(os.path.dirname(__file__), "report.md")


def _load(name):
    path = os.path.join(RESULTS_DIR, name)
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


def _mean(values):
    values = [v for v in values if v is not None]
    return statistics.mean(values) if values else None


def _fmt(x, pct=True):
    if x is None:
        return "—"
    return f"{x * 100:.1f}%" if pct else f"{x:.3f}"


def build_report() -> str:
    lines = ["# Evaluation Report", ""]
    lines.append("Generated by `python -m eval.report` from `eval/results/*.json`. Regenerate after any pipeline change.")
    lines.append("")

    # --- Retrieval metrics --------------------------------------------------
    retrieval = _load("retrieval_metrics.json")
    lines.append("## Retrieval metrics")
    if retrieval:
        k = retrieval["k"]
        rows = retrieval["rows"]
        by_bucket = {}
        for r in rows:
            by_bucket.setdefault(r["bucket"], []).append(r)
        lines.append(f"Ground truth chunk = (source, page) match. k = {k}.")
        lines.append("")
        lines.append("| Bucket | n (with citations) | Recall@k | Precision@k | MRR |")
        lines.append("|---|---|---|---|---|")
        for bucket, bucket_rows in by_bucket.items():
            applicable = [r for r in bucket_rows if r["recall_at_k"] is not None]
            lines.append(
                f"| {bucket} | {len(applicable)} | "
                f"{_fmt(_mean([r['recall_at_k'] for r in applicable]))} | "
                f"{_fmt(_mean([r['precision_at_k'] for r in applicable]))} | "
                f"{_fmt(_mean([r['mrr'] for r in applicable]), pct=False)} |"
            )
        all_applicable = [r for r in rows if r["recall_at_k"] is not None]
        lines.append(
            f"| **overall** | {len(all_applicable)} | "
            f"{_fmt(_mean([r['recall_at_k'] for r in all_applicable]))} | "
            f"{_fmt(_mean([r['precision_at_k'] for r in all_applicable]))} | "
            f"{_fmt(_mean([r['mrr'] for r in all_applicable]), pct=False)} |"
        )
    else:
        lines.append("_Not run — `pytest eval/test_retrieval.py`._")
    lines.append("")

    # --- Citation accuracy ---------------------------------------------------
    citations = _load("citation_metrics.json")
    lines.append("## Citation accuracy & verification")
    if citations:
        applicable = [r for r in citations if r["citation_accuracy"] is not None]
        precisions = [r["citation_accuracy"]["precision"] for r in applicable]
        recalls = [r["citation_accuracy"]["recall"] for r in applicable]
        checked_total = sum(r["citations_checked"] for r in citations)
        verified_total = sum(r["citations_verified"] for r in citations)
        lines.append(
            f"- Citation accuracy (cited page vs. expected page), n={len(applicable)}: "
            f"precision {_fmt(_mean(precisions))}, recall {_fmt(_mean(recalls))}"
        )
        lines.append(
            f"- Citation **verification** (claim text re-embedded and checked against the specific "
            f"cited chunk, similarity ≥ 0.35): {verified_total}/{checked_total} citations verified "
            f"({_fmt(verified_total / checked_total if checked_total else None)})"
        )
    else:
        lines.append("_Not run — `pytest eval/test_citations.py`._")
    lines.append("")

    # --- Abstention confusion matrix -----------------------------------------
    abstention = _load("abstention_matrix.json")
    lines.append("## Abstention confusion matrix")
    if abstention:
        lines.append("| Bucket | correctly_answered | correctly_abstained | hallucinated | wrongly_refused |")
        lines.append("|---|---|---|---|---|")
        for bucket, counts in abstention["by_bucket"].items():
            lines.append(
                f"| {bucket} | {counts.get('correctly_answered', 0)} | "
                f"{counts.get('correctly_abstained', 0)} | {counts.get('hallucinated', 0)} | "
                f"{counts.get('wrongly_refused', 0)} |"
            )
        o = abstention["overall"]
        lines.append(
            f"| **overall** | {o.get('correctly_answered', 0)} | {o.get('correctly_abstained', 0)} | "
            f"**{o.get('hallucinated', 0)}** | {o.get('wrongly_refused', 0)} |"
        )
        lines.append("")
        lines.append(
            "`hallucinated` = answered when the golden set expected a refusal (false positive / made-up "
            "grounding). `wrongly_refused` = abstained when the question was answerable from the docs."
        )
    else:
        lines.append("_Not run — `pytest eval/test_abstention.py`._")
    lines.append("")

    # --- Consistency ----------------------------------------------------------
    consistency = _load("consistency.json")
    lines.append("## Consistency (repeated-run stability)")
    if consistency:
        sims = [r["mean_pairwise_answer_similarity"] for r in consistency]
        agreements = [r["citation_agreement"] for r in consistency]
        n_runs = consistency[0]["runs"] if consistency else 0
        lines.append(
            f"n={len(consistency)} sampled questions × {n_runs} runs each. "
            f"Mean pairwise answer-embedding similarity: {_fmt(_mean(sims), pct=False)}. "
            f"Mean citation-set agreement rate: {_fmt(_mean(agreements))}."
        )
    else:
        lines.append("_Not run — `pytest eval/test_consistency.py`._")
    lines.append("")

    # --- Confidence gate analysis ---------------------------------------------
    gate = _load("gate_analysis.json")
    lines.append("## Confidence gate analysis")
    if gate:
        lines.append(
            "Simulates `config.CONFIDENCE_THRESHOLD` at candidate values against the recorded "
            "pipeline run (no LLM re-calls — see `eval/gate_analysis.py`)."
        )
        lines.append("")
        lines.append("| Threshold | correctly_answered | wrongly_refused | correctly_abstained | hallucinated |")
        lines.append("|---|---|---|---|---|")
        for row in gate:
            t = row["threshold"] if row["threshold"] is not None else "None (disabled)"
            lines.append(
                f"| {t} | {row.get('correctly_answered', 0)} | {row.get('wrongly_refused', 0)} | "
                f"{row.get('correctly_abstained', 0)} | {row.get('hallucinated', 0)} |"
            )
        lines.append("")
        lines.append(
            "**Finding: the gate does not help on this corpus.** Raising the threshold only ever "
            "converts already-correct answers into wrongly-refused ones — answerable and unanswerable "
            "questions produce overlapping top-1 cross-encoder scores (e.g. a genuinely answerable "
            "question scored 0.448 while several correctly-abstained unanswerable questions scored "
            "1.1–3.1). It takes a threshold of ~3.0 to suppress the single hallucination in this run, "
            "but that same threshold wrongly refuses 11 previously-correct answers to do it — a bad "
            "trade. The one hallucination we observed (a deliberately vague query matching a repeated "
            "boilerplate clause) retrieved with a *high* confidence score precisely because the "
            "retrieval was a strong lexical/semantic match — a similarity-threshold gate structurally "
            "cannot catch that failure mode. Recommendation: leave `CONFIDENCE_THRESHOLD = None` "
            "(disabled) until a richer signal than top-1 score (e.g. score *spread* across candidates, "
            "or a query-type classifier) is available to gate on."
        )
    else:
        lines.append("_Not run — `python -m eval.gate_analysis` (requires `pipeline_results.json` from the core suite)._")
    lines.append("")

    # --- RAGAS ------------------------------------------------------------------
    ragas_rows = _load("ragas_metrics.json")
    lines.append("## RAGAS metrics")
    if ragas_rows:
        scored = [r for r in ragas_rows if "error" not in r]
        lines.append(f"n={len(scored)}/{len(ragas_rows)} sampled questions scored successfully.")
        lines.append("")
        lines.append("| Metric | Mean |")
        lines.append("|---|---|")
        for metric in ("faithfulness", "answer_relevancy", "context_precision", "context_recall"):
            lines.append(f"| {metric} | {_fmt(_mean([r.get(metric) for r in scored]), pct=False)} |")
    else:
        lines.append("_Not run — `pytest eval/test_ragas.py` (requires `ragas`; see eval/README.md)._")
    lines.append("")

    return "\n".join(lines)


if __name__ == "__main__":
    report = build_report()
    with open(REPORT_PATH, "w") as f:
        f.write(report)
    print(f"Wrote {REPORT_PATH}")
